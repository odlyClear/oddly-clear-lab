import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const html=await fs.readFile(path.join(root,'dist/water/index.html'),'utf8');
assert.match(html,/<html lang="en">/);
assert.match(html,/Oddly Clear/);
assert.match(html,/\.\.\/assets\/water-full-55s\.mp4/);
assert.ok(!html.includes('__VIDEO_URL__')&&!html.includes('__POSTER_URL__'));
assert.ok(!/<(?:script|link)[^>]+(?:src|href)=["']https?:/i.test(html));
assert.ok(!/[А-Яа-яЁё]/.test(html),'Public interface must remain English-only');
const hash=async p=>createHash('sha256').update(await fs.readFile(path.join(root,p))).digest('hex');
assert.equal(await hash('dist/assets/water-full-55s.mp4'),'a8b99071108a4bf782ec5c99d41b5655d07a0dbf655c3f7a7ffa5bd856e7450b');
const home=await fs.readFile(path.join(root,'dist/index.html'),'utf8');
assert.match(home,/<html lang="en">/);
assert.ok(!/http-equiv="refresh"/i.test(home),'Home must be a real directory, not a redirect');
assert.match(home,/href="\.\/water\/"/);
assert.match(home,/BILgn6OueB0/);
assert.match(home,/@watchoddlyclearlab/);
assert.ok(!/[А-Яа-яЁё]/.test(home),'Home must remain English-only');
assert.ok(!/<script[^>]+src=["']https?:/i.test(home));
assert.ok(!/<link[^>]+rel=["']stylesheet["'][^>]+href=["']https?:/i.test(home));
assert.ok(Buffer.byteLength(home)<250_000,'Home HTML should stay light');
for(const file of ['bricolage-800.ttf','dmsans-400.ttf','dmsans-600.ttf','bricolage-OFL.txt','dmsans-OFL.txt'])assert.ok((await fs.stat(path.join(root,'dist/assets',file))).size>0);
assert.match(html,/All episodes/);
console.log('Static output checked: English, relative URLs, embedded runtime, approved video hash.');
